  assert.equal((await stat()).behind, undefined)
  // both change the same line: not clean, over to the agent
  writeFileSync(join(rig.repo, 'base.txt'), 'main\n')
  g(rig.repo, 'commit', '-qam', 'main says')
  writeFileSync(join(ws.path, 'base.txt'), 'mine\n')
  g(ws.path, 'commit', '-qam', 'the branch says')
  assert.deepEqual((({ behind, ahead, clean }) => [behind, ahead > 0, clean])(await stat()), [1, true, false])
  const head = g(ws.path, 'rev-parse', 'HEAD')
  await assert.rejects(rig.rpc('wsUpdate', { ws: ws.id, how: 'rebase' }), /rebase onto .* stopped \(put back as it was\)/)
