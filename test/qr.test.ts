import assert from 'node:assert/strict'
import { test } from 'node:test'
import { qr, qrPath } from '../src/renderer/src/qr.ts'

test('a URL gives the same QR code as macOS CoreImage (level M); sizes grow with the text', () => {
  // CIQRCodeGenerator, inputCorrectionLevel M, for this URL (each code here was also decoded by Vision)
  const want = [
    '111111100011000010011101001111111',
    '100000100101100110101100001000001',
    '101110101101101110001110001011101',
    '101110101011000000100011101011101',
    '101110101001111110001011001011101',
    '100000101101101001110100101000001',
    '111111101010101010101010101111111',
    '000000001100100010111110000000000',
    '101111100001111001110011101111100',
    '000100011110010001111101001101101',
    '000011101111011101001000111010100',
    '111110000100010111111101100011100',
    '110001111111101110000010110111000',
    '011010010011110101100001001001011',
    '101100101001100110001010111010010',
    '001001010111100100001101011101100',
    '101110111100110111010010010111001',
    '000010010100000010011101001101111',
    '101001111000111110101110011110110',
    '010100000001111010000110111111110',
    '011110100110011000110000110111011',
    '101010011111011110011101011001101',
    '101000111110011001101010100000110',
    '100110010001010010111110011111111',
    '100011110100101001010000111111000',
    '000000001010100011111000100010101',
    '111111100001101101000011101010110',
    '100000101100011001101101100011110',
    '101110101111100110000010111111000',
    '101110101011100101111000110010111',
    '101110101010111111001110001100000',
    '100000100111111100010110010011100',
    '111111101110111101001011110101010',
  ]
  const m = qr('https://charming-tiger-robot-lamp.trycloudflare.com')
  assert.deepEqual(
    m.map(r => r.map(d => (d ? '1' : '0')).join('')),
    want,
  )
  assert.equal(qr('HELLO').length, 21) // version 1
  assert.equal(qr('y'.repeat(400)).length, 77) // version 15
  assert.equal(qr('z'.repeat(1200)).length, 133) // version 29
  assert.throws(() => qr('x'.repeat(3000)), /too long/)
  assert.match(qrPath(qr('HELLO')), /^M4 4h1v1h-1z/) // the top left finder, after the quiet zone
})
